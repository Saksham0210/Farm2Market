const I18N_STORAGE_KEY = "farmcircle_lang";
const I18N_DEFAULT_LANG = "en";
 
function applyTranslations(lang) {
    const dict = TRANSLATIONS[lang] || TRANSLATIONS[I18N_DEFAULT_LANG];

    // HTML key -> translation key aliases
    const aliases = {
        hero_description: "hero_p",

        role_farmer: "opt_farmer",
        role_buyer: "opt_buyer",
        role_logistics: "opt_logistics",

        label_full_name: "label_fullname",
        label_farm_name: "label_farmname",
        label_pickup_location: "label_pickup",
        label_buyer_type: "label_buyertype",
        label_business_name: "label_business",
        label_default_location: "label_defaultloc",

        buyer_individual: "opt_individual",
        buyer_bulk: "opt_bulk",

        how1: "how_li1",
        how2: "how_li2",
        how3: "how_li3",
        how4: "how_li4",
        how5: "how_li5",

        support_tag: "support_eyebrow",
        support_title: "support_h2",
        support_description: "support_p",

        helpline_title: "helpline_h3",
        helpline_description: "helpline_p",

        agent_title: "agent_h3",
        agent_description: "agent_p",

        btn_call: "call_btn",
        btn_agent: "agent_btn"
    };

    document.querySelectorAll("[data-i18n]").forEach(el => {

        let key = el.dataset.i18n;

        if (dict[key] === undefined && aliases[key]) {
            key = aliases[key];
        }

        if (dict[key] !== undefined) {
            el.textContent = dict[key];
        }
    });

    document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {

        let key = el.dataset.i18nPlaceholder;

        if (dict[key] === undefined && aliases[key]) {
            key = aliases[key];
        }

        if (dict[key] !== undefined) {
            el.placeholder = dict[key];
        }
    });

    document.documentElement.lang = lang;

    document.documentElement.dir =
        ["ur", "sd"].includes(lang) ? "rtl" : "ltr";
}

function setLanguage(lang) {

    if (!TRANSLATIONS[lang]) {
        lang = I18N_DEFAULT_LANG;
    }

    try {
        localStorage.setItem(I18N_STORAGE_KEY, lang);
    } catch (e) {}

    applyTranslations(lang);

    const select = document.getElementById("lang-select");

    if (select) {
        select.value = lang;
    }

    document.title =
        TRANSLATIONS[lang].page_title ||
        TRANSLATIONS[I18N_DEFAULT_LANG].page_title;
}
 
function getInitialLanguage() {
  try {
    const saved = localStorage.getItem(I18N_STORAGE_KEY);
    if (saved && TRANSLATIONS[saved]) return saved;
  } catch (e) {
    // ignore
  }
  // Fall back to the browser's language if we support it (e.g. "hi-IN" -> "hi")
  const browserLang = (navigator.language || "").split("-")[0];
  if (TRANSLATIONS[browserLang]) return browserLang;
  return I18N_DEFAULT_LANG;
}
 
document.addEventListener("DOMContentLoaded", () => {
  const initialLang = getInitialLanguage();
  applyTranslations(initialLang);
 
  const select = document.getElementById("lang-select");
  if (select) {
    select.value = initialLang;
    select.addEventListener("change", (e) => setLanguage(e.target.value));
  }
});